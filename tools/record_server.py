"""Qalam recording studio server.

Serves the project like `python3 -m http.server`, and also accepts recordings from
tools/record.html.  A recording is cleaned (trim + level) with ffmpeg, saved over the computer-voice
clip in assets/audio/, added to js/audio-manifest.js, and listed in tools/human-recorded.json so
tools/make-audio.js never replaces it.

Run from the project folder:   python3 tools/record_server.py      (then open http://localhost:8765/tools/record.html)
"""
import hashlib, json, os, re, subprocess, sys, tempfile, unicodedata
from http.server import SimpleHTTPRequestHandler, ThreadingHTTPServer
from urllib.parse import urlparse, parse_qs

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..'))
AUDIO = os.path.join(ROOT, 'assets', 'audio')
MANIFEST = os.path.join(ROOT, 'js', 'audio-manifest.js')
HUMAN = os.path.join(ROOT, 'tools', 'human-recorded.json')
CLEAN = ("highpass=f=70,silenceremove=start_periods=1:start_threshold=-42dB:start_silence=0.05,areverse,"
         "silenceremove=start_periods=1:start_threshold=-42dB:start_silence=0.12,areverse,"
         "loudnorm=I=-16:TP=-1.5:LRA=11,apad=pad_dur=0.08")

def key(t): return unicodedata.normalize('NFC', t).strip()
def clip_id(t): return hashlib.sha1(key(t).encode()).hexdigest()[:10]   # same ids as tools/make-audio.js

def read_manifest():
    if not os.path.exists(MANIFEST): return {}
    s = open(MANIFEST, encoding='utf-8').read()
    return json.loads(s[s.index('{'):s.rindex('}') + 1])

def write_manifest(m):
    with open(MANIFEST, 'w', encoding='utf-8') as f:
        f.write('/* generated by tools/make-audio.js */\nwindow.QQ_AUDIO = ' + json.dumps(m, ensure_ascii=False, separators=(',', ':')) + ';\n')

def read_human():
    return json.load(open(HUMAN, encoding='utf-8')) if os.path.exists(HUMAN) else {}

class Handler(SimpleHTTPRequestHandler):
    def __init__(self, *a, **kw): super().__init__(*a, directory=ROOT, **kw)

    def end_headers(self):
        self.send_header('Cache-Control', 'no-store')
        self.send_header('Accept-Ranges', 'bytes')
        super().end_headers()

    def send_json(self, code, obj):
        body = json.dumps(obj, ensure_ascii=False).encode()
        self.send_response(code); self.send_header('Content-Type', 'application/json'); self.send_header('Content-Length', str(len(body))); self.end_headers(); self.wfile.write(body)

    def do_GET(self):
        if urlparse(self.path).path == '/api/human':
            return self.send_json(200, read_human())
        rng = self.headers.get('Range')
        if rng and self.send_range(rng): return
        return super().do_GET()

    def send_range(self, rng):
        """Byte-range replies (206). Safari and iOS only play audio from servers that support them."""
        path = self.translate_path(self.path)
        m = re.match(r'bytes=(\d*)-(\d*)$', rng.strip())
        if not m or not os.path.isfile(path): return False
        size = os.path.getsize(path)
        start, end = m.group(1), m.group(2)
        if start == '': start, end = max(0, size - int(end or 0)), size - 1   # suffix range: last N bytes
        else: start, end = int(start), min(int(end) if end else size - 1, size - 1)
        if start >= size or start > end:
            self.send_response(416); self.send_header('Content-Range', f'bytes */{size}'); self.end_headers(); return True
        self.send_response(206)
        self.send_header('Content-Type', self.guess_type(path))
        self.send_header('Accept-Ranges', 'bytes')
        self.send_header('Content-Range', f'bytes {start}-{end}/{size}')
        self.send_header('Content-Length', str(end - start + 1))
        self.end_headers()
        with open(path, 'rb') as f:
            f.seek(start); self.wfile.write(f.read(end - start + 1))
        return True

    def do_POST(self):
        u = urlparse(self.path)
        if u.path != '/api/record': return self.send_json(404, {'error': 'not found'})
        text = key(parse_qs(u.query).get('text', [''])[0])
        if not text or not re.search(r'[ء-ي]', text) or len(text) > 40:
            return self.send_json(400, {'error': 'bad text'})
        n = int(self.headers.get('Content-Length', 0))
        if n <= 0 or n > 5_000_000: return self.send_json(400, {'error': 'bad size'})
        raw = tempfile.mktemp(suffix='.webm')
        with open(raw, 'wb') as f: f.write(self.rfile.read(n))
        cid = clip_id(text); dst = os.path.join(AUDIO, cid + '.mp3')
        try:
            subprocess.run(['ffmpeg', '-loglevel', 'error', '-y', '-i', raw, '-af', CLEAN, '-ar', '24000', '-ac', '1', '-b:a', '64k', dst], check=True)
        except subprocess.CalledProcessError:
            return self.send_json(500, {'error': 'could not convert the recording'})
        finally:
            os.remove(raw)
        if os.path.getsize(dst) < 2000:
            os.remove(dst); return self.send_json(400, {'error': 'recording was silent — check the microphone'})
        m = read_manifest(); m[text] = cid; write_manifest(m)
        h = read_human(); h[text] = cid
        json.dump(h, open(HUMAN, 'w', encoding='utf-8'), ensure_ascii=False, indent=1)
        self.send_json(200, {'ok': True, 'id': cid, 'file': f'assets/audio/{cid}.mp3'})

if __name__ == '__main__':
    port = int(sys.argv[1]) if len(sys.argv) > 1 else 8765
    print(f'Qalam studio: http://localhost:{port}/tools/record.html')
    ThreadingHTTPServer(('127.0.0.1', port), Handler).serve_forever()
