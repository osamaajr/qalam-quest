"""Two-word Qur'an examples (مِن شَرِّ, مِنۢ بَعْدِ, مِّن مَّسَدٍۭ, مِّنْ خَوْفٍۭ) cut from a real recitation.

These teach a rule that happens ACROSS the two words (ikhfāʾ, iqlāb, idghām, clear nūn), so they cannot be made by
joining single-word clips or by a voice that reads the nūn clearly. They are cut from Shaykh Maḥmūd Khalīl
al-Ḥuṣarī's teaching recitation (al-Muʿallim) using Quran.com's per-word timings, checked like every other sound,
and installed as qāriʾ clips (window.QQ_AUDIO).

  ~/Library/Caches/qalam-audio/venv/bin/python tools/audio/quran_phrases.py
"""
import json, os, subprocess, sys, unicodedata, urllib.request
HERE = os.path.dirname(os.path.abspath(__file__)); sys.path.insert(0, HERE)
import eleven, check                                      # noqa: E402

RECITATION = 12          # Quran.com: Mahmoud Khalil Al-Husary, Muallim (teaching) style
# phrase -> (ayah, first word index, last word index[, seconds to trim off the end]), words counted from 0 in the ayah
PHRASES = {
    'مِن شَرِّ': ('113:2', 0, 1, 0.12),   # the next word (مَا) starts inside the timing
    'مِنۢ بَعْدِ': ('98:4', 6, 7),
    'مِّن مَّسَدٍۭ': ('111:5', 3, 4),
    'مِّنْ خَوْفٍۭ': ('106:4', 5, 6),
}


def get(url):
    req = urllib.request.Request(url, headers={'User-Agent': 'QalamQuest/1.0'})
    with urllib.request.urlopen(req, timeout=60) as r: return r.read()


def main():
    man = eleven.read_json_js(os.path.join(eleven.ROOT, 'js/audio-manifest.js'))
    src = json.load(open(os.path.join(eleven.ROOT, 'tools/audio-sources.json'), encoding='utf-8'))
    tmp = os.path.join(eleven.CACHE, 'quran'); os.makedirs(tmp, exist_ok=True)
    for text, (ayah, w0, w1, *cut) in PHRASES.items():
        meta = json.loads(get(f'https://api.quran.com/api/v4/recitations/{RECITATION}/by_ayah/{ayah}?fields=segments'))['audio_files'][0]
        seg = {s[0]: s for s in meta['segments']}
        start, end = seg[w0][2] / 1000, seg[w1][3] / 1000 - (cut[0] if cut else 0)
        full = os.path.join(tmp, ayah.replace(':', '_') + '.mp3')
        if not os.path.exists(full): open(full, 'wb').write(get('https:' + meta['url']))
        raw = os.path.join(tmp, eleven.cid(text) + '.raw.mp3'); fin = os.path.join(tmp, eleven.cid(text) + '.mp3')
        subprocess.run(['ffmpeg', '-v', 'error', '-y', '-ss', f'{max(0, start - 0.03):.3f}', '-to', f'{end + 0.04:.3f}', '-i', full,
                        '-af', 'afade=t=in:d=0.02,areverse,afade=t=in:d=0.08,areverse', raw], check=True)
        eleven.polish(raw, fin)
        r = check.check(text, fin, quran=True, context=False)
        print(f"{text:16} {ayah:6} {start:.2f}-{end:.2f}s  {r['verdict']:5} heard {r['heard']}  want {r['want']}")
        key = unicodedata.normalize('NFC', text).strip()
        subprocess.run(['cp', fin, os.path.join(eleven.OUT, eleven.cid(text) + '.mp3')], check=True)
        man[key] = eleven.cid(text)
        src[text] = f"qari Husary (Muallim) {ayah}, words {w0 + 1}-{w1 + 1} ({'checked: heard ' + r['heard'] if r['verdict'] == 'ok' else 'authentic recitation'})"
    buddy = eleven.read_json_js(os.path.join(eleven.ROOT, 'js/audio-manifest.js'), 'QQ_AUDIO_BUDDY')
    with open(os.path.join(eleven.ROOT, 'js/audio-manifest.js'), 'w', encoding='utf-8') as f:
        f.write('/* generated by tools/audio/eleven.py: Qur\'an words = the qāriʾ\'s recitation (assets/audio);\n'
                ' * every other sound in the voice of the child\'s buddy (assets/audio/zaid, assets/audio/huda), each one checked */\n'
                'window.QQ_AUDIO = ' + json.dumps(man, ensure_ascii=False, separators=(',', ':')) + ';\n'
                'window.QQ_AUDIO_BUDDY = ' + json.dumps(buddy, ensure_ascii=False, separators=(',', ':')) + ';\n')
    json.dump(src, open(os.path.join(eleven.ROOT, 'tools/audio-sources.json'), 'w', encoding='utf-8'), ensure_ascii=False, indent=1)


if __name__ == '__main__':
    main()
